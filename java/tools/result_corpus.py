# -*- coding: utf-8 -*-
"""「查询结果渲染成表格」的金标准语料：两条线各写一份渲染器，必须逐字符对得上。

挑的都是现场真会读不出来的形状：中文列名与中文取值混着排（宽度算法一错就错行）、
NULL 与空串同列、取值里带换行与制表符（会把整张表顶散）、单个格子超长（要截断）、
零行、没有列名、几十列、全角字母与生僻字的宽字符区间。

取值一律写成字符串或 None，不放数字：Python 的 str(1e10) 与 Java 的
Double.toString 本来就不一样，那属于两侧语言的标准库差异，不是渲染器的行为，
混进金标准只会制造假红。
"""

TABLE_CASES = [
    # 中英混排：宽度算错就错行
    (["id", "名称", "amount"],
     [["1", "某公司", "3.50"], ["10", None, "-007"], ["7", "很短", ""]]),

    # 零行：只有表头，表头下面那条线就是收口
    (["a"], []),

    # 完全没有列名：不画表，交给调用方只报行数
    ([], [["1"]]),

    # 取值里带换行 / 制表符 / 超长：必须折成可见转义并截断
    (["备注"], [["一行\n两行"], ["带\t制表"], ["x" * 60], ["尾行\r\n换行"]]),

    # 全角字母、中日韩符号、生僻字与 emoji 都落在宽字符区间里
    (["全角", "假名", "生僻", "标记"],
     [["ＲＥＳＵＬＴ", "アイウ", "𠀀", "★"], ["①", "ー", "￦", "‥"]]),

    # 列数多：边框与列序不能错
    (["表名", "列名", "类型", "长度", "主键", "注释"],
     [["ods_t_order", "id", "BIGINT", "20", "是", "主键"],
      ["ods_dim_area", "area_code", "VARCHAR", "64", "否", None]]),

    # 行比列短 / 比列长：缺的补空、多的不看，都不能崩
    (["c1", "c2", "c3"], [["只有两个值", None], ["一", "二", "三", "四"]]),

    # 空串与 NULL 同列：两种都要看得出区别
    (["值", "说明"], [["", "空串"], [None, "NULL"], [" ", "只有一个空格"]]),
]
